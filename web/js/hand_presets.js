/* 手部預設動作 —— 唯一的定義處。
 *
 * 誰在讀這一份：
 *   HandControlInterface.html   預設動作按鈕
 *   HandMotionInterface.html    張開按鈕
 *   src/strategy/strategy/API.py   api.handPreset('握拳')
 *
 * 改完：網頁重新載入就生效；策略要重跑（API.py 啟動時讀一次）。
 *
 * ── 為什麼是 .js 而不是 .json ──────────────────────────────────────────
 * 曾經改成 .json 再用 fetch() 讀，結果網頁用 file:// 開的時候會被 CORS 擋掉
 * （origin 是 null），畫面顯示「讀不到 js/hand_presets.json」。
 * <script src> 不受 CORS 限制，file:// 和 http:// 都能用，所以改回 .js。
 * 下面那個物件刻意寫成**嚴格 JSON**（雙引號、沒有尾逗號、物件裡面沒有註解），
 * 這樣 API.py 可以把 { ... } 整段切出來直接 json.loads，不用另外維護一份。
 * ──────────────────────────────────────────────────────────────────────
 *
 * 關節順序（和 HandControl 的滑桿、HandMotion 的 L1~L6 一致）：
 *   1 拇指彎曲  2 拇指橫擺  3 食指  4 中指  5 無名指  6 小指
 *
 * pos 0~255：0 收到底、255 張到底。
 * spd 10~255：越大越快。不要填 0 —— 節點把 0 當「不改速度」，
 *             而 SDK 只要收到一個超出 10~255 的值就會把整包速度丟掉。
 *
 * 左右手共用同一組數值 —— 上游的 O6 本來就是這樣，不需要鏡像轉換。
 * 原始數值出自官方 gui_control/config/constants.py 的 O6 preset_actions。
 */

